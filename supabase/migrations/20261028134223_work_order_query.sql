create table public.work_orders (
 id uuid primary key default gen_random_uuid(),
 number integer generated by default as identity unique check(number>0),
 project_id uuid not null references public.projects(id),
 creator_id uuid not null references public.profiles(id),
 assignee_id uuid not null references public.profiles(id),
 created_at timestamptz not null default now(),
 status text not null default 'pending' check(status in ('pending','completed','rejected')),
 severity text not null check(severity in ('minor','normal','major','urgent')),
 discipline text not null check(discipline in ('architecture','structure','plumbing')),
 description text not null check(length(trim(description))>0),
 location text not null check(length(trim(location))>0),
 details text, root_cause text, prevention text, seed_key text unique,
 check ((status='completed' and length(trim(root_cause))>0 and root_cause is not null)
 or (status in ('pending','rejected') and root_cause is null and prevention is null))
);
create index work_orders_creator on public.work_orders(project_id,creator_id);
create index work_orders_assignee on public.work_orders(project_id,assignee_id);
create table public.work_order_records (
 id uuid primary key default gen_random_uuid(),
 work_order_id uuid not null references public.work_orders(id),
 actor_id uuid not null references public.profiles(id),
 occurred_at timestamptz not null,
 action text not null check(action in ('created','edited','resolved','rejected','assigned','reopened')),
 reason text, changes jsonb not null default '{}'::jsonb,
 root_cause text, prevention text, seed_key text unique,
 check(jsonb_typeof(changes)='object'),
 check((changes - array['status','assignee_id','severity','discipline','description','location','details','root_cause','prevention'])='{}'::jsonb),
 check(action<>'resolved' or (root_cause is not null and length(trim(root_cause))>0)),
 check(action not in ('rejected','assigned','reopened') or (reason is not null and length(trim(reason))>0))
);
create index work_order_records_time on public.work_order_records(work_order_id,occurred_at,id);
create index work_order_records_actor on public.work_order_records(actor_id);
create index work_orders_creator_fk on public.work_orders(creator_id);
create index work_orders_assignee_fk on public.work_orders(assignee_id);

create function private.current_role() returns text
language sql stable security definer set search_path='' as $$
 select m.role from public.project_memberships m where m.id=private.current_membership() and m.user_id=auth.uid()
$$;
create function private.can_read_work_order(target uuid) returns boolean
language sql stable security definer set search_path='' as $$
 select auth.uid() is not null and exists(
 select 1 from public.work_orders w where w.id=target and w.project_id=private.current_project()
 and (private.current_role()='admin' or (private.current_role()='inspector' and w.creator_id=auth.uid())
 or (private.current_role()='contractor' and w.assignee_id=auth.uid())))
$$;
create function private.work_order_people(target integer) returns jsonb
language plpgsql stable security definer set search_path='' as $$
declare w public.work_orders;
begin
 select * into w from public.work_orders where number=target;
 if w.id is null or not private.can_read_work_order(w.id) then return '{}'::jsonb; end if;
 return (select coalesce(jsonb_object_agg(p.id::text,p.name),'{}'::jsonb) from public.profiles p
 where p.id in (w.creator_id,w.assignee_id) or exists(select 1 from public.work_order_records r
 where r.work_order_id=w.id and (r.actor_id=p.id or r.changes->'assignee_id'->>'before'=p.id::text
 or r.changes->'assignee_id'->>'after'=p.id::text)));
end $$;
create function private.work_order_exists(target integer) returns boolean
language sql stable security definer set search_path='' as $$
 select private.current_membership() is not null and auth.uid() is not null
 and exists(select 1 from public.work_orders where number=target)
$$;
alter table public.work_orders enable row level security;
alter table public.work_order_records enable row level security;
revoke all on public.work_orders,public.work_order_records from public,anon,authenticated;
grant select on public.work_orders,public.work_order_records to authenticated;
grant all on public.work_orders,public.work_order_records to service_role;
grant usage,select,update on sequence public.work_orders_number_seq to service_role;
create policy work_orders_read on public.work_orders for select to authenticated
 using(private.can_read_work_order(id));
create policy work_order_records_read on public.work_order_records for select to authenticated
 using(private.can_read_work_order(work_order_id));

create function public.list_work_orders(p_status text default 'pending',p_sort text default 'newest') returns jsonb
language plpgsql stable security invoker set search_path='' as $$
declare result jsonb;
begin
 if private.current_membership() is null or private.current_role() not in ('inspector','contractor') then
 raise exception '当前身份不可读取普通列表' using errcode='42501'; end if;
 select coalesce(jsonb_agg(q.item order by q.urgent desc,q.time_asc asc,q.time_desc desc,q.num_asc asc,q.num_desc desc),'[]'::jsonb) into result from (
 select jsonb_build_object('number',w.number,'status',w.status,'severity',w.severity,'discipline',w.discipline,
 'description',w.description,'location',w.location,'createdAt',w.created_at,
 'assignee',jsonb_build_object('id',w.assignee_id,'name',private.work_order_people(w.number)->>w.assignee_id::text),'photos','[]'::jsonb) item,
 w.severity='urgent' urgent,
 case when p_sort='oldest' then w.created_at end time_asc,
 case when p_sort<>'oldest' or p_sort is null then w.created_at end time_desc,
 case when p_sort='oldest' then w.number end num_asc,
 case when p_sort<>'oldest' or p_sort is null then w.number end num_desc
 from public.work_orders w where w.project_id=private.current_project()
 and ((private.current_role()='inspector' and w.creator_id=auth.uid()) or (private.current_role()='contractor' and w.assignee_id=auth.uid()))
 and (p_status='all' or (p_status='ended' and w.status in ('completed','rejected')) or
 ((p_status is null or p_status not in ('all','ended')) and w.status='pending'))
 ) q;
 return result;
end $$;
create function public.get_work_order(p_number integer) returns jsonb
language plpgsql stable security invoker set search_path='' as $$
declare w public.work_orders; people jsonb; history jsonb; project_name text;
begin
 if private.current_membership() is null then raise exception '请先选择有效身份' using errcode='42501'; end if;
 select * into w from public.work_orders where number=p_number;
 if w.id is null then return jsonb_build_object('kind',case when private.work_order_exists(p_number) then 'forbidden' else 'not_found' end); end if;
 people:=private.work_order_people(p_number);
 select name into project_name from public.projects where id=w.project_id;
 select coalesce(jsonb_agg(jsonb_build_object('id',r.id,'action',r.action,
 'actor',jsonb_build_object('id',r.actor_id,'name',people->>r.actor_id::text),
 'occurredAt',r.occurred_at,'reason',r.reason,'changes',r.changes,'rootCause',r.root_cause,'prevention',r.prevention)
 order by r.occurred_at desc,r.id desc),'[]'::jsonb) into history from public.work_order_records r where r.work_order_id=w.id;
 return jsonb_build_object('kind','ok','detail',jsonb_build_object(
 'number',w.number,'status',w.status,'severity',w.severity,'discipline',w.discipline,
 'description',w.description,'location',w.location,'createdAt',w.created_at,
 'creator',jsonb_build_object('id',w.creator_id,'name',people->>w.creator_id::text),
 'assignee',jsonb_build_object('id',w.assignee_id,'name',people->>w.assignee_id::text),
 'project',jsonb_build_object('id',w.project_id,'name',project_name),
 'details',w.details,'rootCause',w.root_cause,'prevention',w.prevention,'records',history,'people',people,'photos','[]'::jsonb));
end $$;
-- Only offline demo preparation may synchronize the identity sequence.
create function public.sync_work_order_sequence() returns void
language sql security invoker set search_path='' as $$
 select setval('public.work_orders_number_seq',greatest(coalesce((select max(number) from public.work_orders),0)+1,1),false)
$$;
revoke all on function private.current_role(),private.can_read_work_order(uuid),private.work_order_people(integer),private.work_order_exists(integer) from public,anon,authenticated;
grant execute on function private.current_role(),private.can_read_work_order(uuid),private.work_order_people(integer),private.work_order_exists(integer) to authenticated;
revoke all on function public.list_work_orders(text,text),public.get_work_order(integer) from public,anon,authenticated;
grant execute on function public.list_work_orders(text,text),public.get_work_order(integer) to authenticated;
revoke all on function public.sync_work_order_sequence() from public,anon,authenticated;
grant execute on function public.sync_work_order_sequence() to service_role;
